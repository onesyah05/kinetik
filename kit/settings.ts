/** Shared types/defaults (no React import, safe for the server). */

export type CaptionStyle = 'tiktok' | 'classic' | 'karaoke';
export type CaptionPosition = 'bottom' | 'center' | 'top';

export type CaptionSettings = {
  enabled: boolean;
  style: CaptionStyle;
  position: CaptionPosition;
  /** Font size in px. 0 = automatic (based on video size). */
  fontSize: number;
  color: string;
  highlightColor: string;
  fontFamily: string;
  wordsPerPage: number;
  uppercase: boolean;
};

export type ProjectSettings = {
  id: string;
  name: string;
  width: number;
  height: number;
  fps: number;
  durationInFrames: number;
  captions: CaptionSettings;
  /** How the agent offers style options on a new video: AI-generated frames (default when image generation is set up) or live code samples. */
  styleFrames?: 'ai' | 'code';
  /** Several videos sharing this project's style and assets. Absent = just src/Video.tsx. */
  videos?: VideoEntry[];
  /** Which video the preview, agent and render work on ('main' = src/Video.tsx). */
  activeVideo?: string;
};

export type VideoEntry = {id: string; name: string; durationInFrames: number; theme?: string};

export type Word = {text: string; start: number; end: number};

/** Generated by the `tts` tool into src/voiceover/<name>.ts */
export type VoiceTrack = {
  src: string;
  text: string;
  voice: string;
  durationInSeconds: number;
  words: Word[];
};

export const defaultCaptions: CaptionSettings = {
  enabled: true,
  style: 'tiktok',
  position: 'bottom',
  fontSize: 0,
  color: '#ffffff',
  highlightColor: '#facc15',
  fontFamily: 'Inter, "Segoe UI", system-ui, sans-serif',
  wordsPerPage: 3,
  uppercase: true,
};

